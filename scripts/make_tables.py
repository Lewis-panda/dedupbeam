"""Write results/tables.md (every number behind the figures) from the result JSON files.
Usage: python scripts/make_tables.py"""

import _data as D
from dedupbeam import predict

GiB = D.GiB


def f(x, d=1):
    return "—" if x is None else f"{x:,.{d}f}"


def x_(v):
    return "—" if v is None else f"{v:.2f}×"


def pct(meas, pred):
    if meas is None or pred is None:
        return "—"
    if pred == 0:
        return "exact" if meas == 0 else "—"
    return "exact" if meas == pred else f"{(meas - pred) / pred * 100:+.2f}%"


def status(r):
    if r is None:
        return "not run"
    return {
        "skipped_host_memory": "not run: host memory",
        "gpu_oom": "not run: GPU memory",
    }.get(r.get("status"), r.get("status"))


o = [
    "# Result tables",
    "",
    "Generated by `scripts/make_tables.py` from `results/**/*.json`. GiB = 2^30 bytes. All runs: step-wise beam search, "
    "beam width 2 (half of the beams survive each step and each survivor is expanded into 2), cumulative log-probability "
    "scoring, Gumbel-max sampling with seed 0, prompt 128 tokens, 1,920 generated tokens, FP16.",
    "",
]

# ---------------------------------------------------------------- machine
m = D.machine()
t = m["transfer"]
o += [
    "## Machine",
    "",
    "| Item | Value |",
    "|---|---|",
    f"| GPU | {m['versions']['gpu']}, driver {m['versions']['driver']}, PyTorch {m['versions']['torch']} (CUDA {m['versions']['cuda']}) |",
    f"| PCIe link while transferring | {m['pcie_during_transfer']['sysfs_seen'][0][0]}, x{m['pcie_during_transfer']['sysfs_seen'][0][1]} |",
    f"| Host→GPU, pinned, 1 GiB (median of {t['h2d_pinned_1 GiB']['reps']}) | {t['h2d_pinned_1 GiB']['gib_per_s']:.2f} GiB/s ({t['h2d_pinned_1 GiB']['gb_per_s']:.2f} GB/s) |",
    f"| GPU→host, pinned, 1 GiB | {t['d2h_pinned_1 GiB']['gib_per_s']:.2f} GiB/s |",
    f"| Free GPU memory after loading FP16 OPT-2.7B | {m['gpu_memory']['free_after_model_mib']:,.0f} MiB of {m['gpu_memory']['total_mib']:,.0f} MiB |",
    f"| FP16 matmul (131,072 × 2,560) × (2,560 × 2,560) | {m['matmul']['median_s'] * 1e3:.1f} ms ({m['matmul']['tflops']:.1f} TFLOPS) |",
    f"| Host memory | {m['pin_test']['mem_total_gib']:.1f} GiB; {m['pin_test']['pinned_gib']:.0f} GiB could be pinned |",
    "",
]

# ---------------------------------------------------------------- reproduction
bw = D.h2d_gib_per_s()
R1 = D.repro_runs()
o += [
    "## LBS reproduction (one KV copy per beam, OPT-2.7B, M = 8 GiB, step 32)",
    "",
    f"Predicted transfer: the paper's Eq. 1–5. Predicted transfer time: predicted bytes ÷ {bw:.2f} GiB/s.",
    "",
    "| Beams | KV at the end | Baseline: transfer predicted / measured (GiB) | LBS: predicted / measured (GiB) | Baseline: transfer time pred. / meas. (s) | LBS: pred. / meas. (s) | Baseline total (s) | LBS total (s) | LBS speedup |",
    "|---|---|---|---|---|---|---|---|---|",
]
for n, r in R1.items():
    pb, pl = predict.baseline_dm(n, 8 * GiB), predict.lbs_dm(n, 8 * GiB)
    b, l = r["baseline"], r["lbs"]
    if not (D.ok(b) and D.ok(l)):
        o.append(
            f"| {n} | {f(D.percopy_kv_bytes(n) / GiB, 2)} GiB | | | | | {status(b)} | {status(l)} | |"
        )
        continue
    o.append(
        f"| {n} | {D.percopy_kv_bytes(n) / GiB:.2f} GiB | {f(pb / GiB)} / {f(b['h2d_bytes'] / GiB)} | {f(pl / GiB)} / {f(l['h2d_bytes'] / GiB)} "
        f"| {f(pb / GiB / bw)} / {f(b['h2d_s'])} | {f(pl / GiB / bw)} / {f(l['h2d_s'])} | {f(b['total_s'])} | {f(l['total_s'])} "
        f"| {b['total_s'] / l['total_s']:.2f}× |"
    )
o += [""]

# ---------------------------------------------------------------- dedup experiment
R = D.dedup_runs()
o += [
    "## Deduplication experiment (OPT-2.7B, 32 beams)",
    "",
    "Each step length has one reference run (per-beam baseline at M = 2.2 GiB, sampling freely); every other run takes its "
    'tokens from that run\'s beam tree, so all runs of a step length do the same work. "Other" = GPU→host + GPU-side '
    "rearrangement + pruning. Predicted transfer: per-beam runs use the paper's Eq. 1–5; dedup runs use a GPU-free replay "
    "of the reference beam tree (`dedupbeam/segbook.py`).",
    "",
]
for T in D.STEPS:
    o += [
        f"### Step {T} ({1920 // T} steps)",
        "",
        "| Method | M (GiB) | Transfer measured (GiB) | Transfer predicted (GiB) | Match | Transfer (s) | Compute (s) | Other (s) | Total (s) | KV on GPU, peak (GiB) | LBS groups, max |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    rows = [(st, mo, lab, D.M_MAIN) for st, mo, lab in D.METHODS]
    rows += [
        ("dedup", "baseline", "Baseline, dedup KV", D.M_CTRL),
        ("dedup", "lbs", "LBS, dedup KV", D.M_CTRL),
        ("dedup", "baseline", "Baseline, dedup KV", D.M_SUPP),
        ("dedup", "lbs", "LBS, dedup KV", D.M_SUPP),
    ]
    for st, mo, lab, M in rows:
        r = D.run("dedup", st, mo, D.N_DEDUP, T, M)
        if not D.ok(r):
            o.append(f"| {lab} | {M:g} | {status(r)} | | | | | | | | |")
            continue
        pred = D.predicted_h2d(st, mo, T, M)
        o.append(
            f"| {lab} | {M:g} | {f(r['h2d_bytes'] / GiB)} | {f(None if pred is None else pred / GiB)} | {pct(r['h2d_bytes'], pred)} "
            f"| {f(r['h2d_s'])} | {f(r['compute_s'])} | {f(D.other_s(r))} | {f(r['total_s'])} "
            f"| {f(r.get('kv_gpu_peak_bytes', 0) / GiB, 2)} | {r['max_groups'] if mo == 'lbs' else '—'} |"
        )
    o += [""]
o += [
    '"KV on GPU, peak" for a baseline includes the scratch buffer for the layer being computed, which is outside M '
    "(so it can exceed M slightly).",
    "",
]

sp = D.speedups(R)
o += [
    "### Speedups (ratios of total time, M = 2.2 GiB)",
    "",
    "| Step | LBS vs baseline, per-beam KV | LBS vs baseline, both dedup | Dedup vs per-beam, baseline | Dedup vs per-beam, LBS |",
    "|---|---|---|---|---|",
]
for T in D.STEPS:
    s_ = sp[T]
    o.append(
        f"| {T} | {x_(s_['lbs_vs_base_percopy'])} | {x_(s_['lbs_vs_base_dedup'])} | {x_(s_['dedup_vs_percopy_base'])} | {x_(s_['dedup_vs_percopy_lbs'])} |"
    )
o += [
    "",
    "LBS vs baseline with dedup KV at M = 1 GiB (supplementary): "
    + ", ".join(
        f"step {T} {x_(D.ratio(D.run('dedup', 'dedup', 'baseline', 32, T, 1), D.run('dedup', 'dedup', 'lbs', 32, T, 1)))}"
        for T in D.STEPS
    )
    + ".",
    "",
]

o += [
    "### KV size: one copy per beam vs deduplicated",
    "",
    "| Step | One copy per beam, end of search (GiB) | Distinct KV, peak after a step is written (GiB) | Distinct KV, peak after pruning (GiB) | Buffers if shared runs were merged (max) | Attention buffers per layer used |",
    "|---|---|---|---|---|---|",
]
for T in D.STEPS:
    r = R[T][("dedup", "baseline")]
    if D.ok(r):
        o.append(
            f"| {T} | {D.percopy_kv_bytes() / GiB:.2f} | {r['unique_kv_peak_bytes'] / GiB:.2f} | {r['unique_kv_peak_after_prune_bytes'] / GiB:.2f} "
            f"| {r['max_merged_buffers']} | {r['buffers_per_layer_used']} |"
        )
o += [""]

o += [
    "### Same work across methods (runs that follow the reference tree)",
    "",
    "Under FP16, a different batch size or KV layout changes rounding, so a run that samples on its own eventually "
    "picks a different token. Forced runs take every token from the reference tree; the table shows how close their "
    "own computation is.",
    "",
    "| Step | Method | M | Max per-token log-prob difference | Own sample differs / samples | Steps with a different pruning choice |",
    "|---|---|---|---|---|---|",
]
for T in D.STEPS:
    for st, mo, lab in D.METHODS[1:]:
        for M in (D.M_MAIN, D.M_CTRL, D.M_SUPP):
            r = D.run("dedup", st, mo, D.N_DEDUP, T, M)
            if D.ok(r) and r.get("forced_from"):
                fs = r["force_stats"]
                o.append(
                    f"| {T} | {lab} | {M:g} | {fs['max_lp_diff']:.4f} | {fs['own_differs']:,} / {fs['samples']:,} | {fs['prune_differs']} |"
                )
o += [""]

# ---------------------------------------------------------------- GQA
G = D.gqa_runs()
cfg = D.gqa_config() or {}
btok = cfg.get("kv_bytes_per_token_all_layers", 36864)
o += [
    "## GQA comparison (Qwen2.5-3B, one KV copy per beam, M = 8 GiB, step 32)",
    "",
    f"Qwen2.5-3B: {cfg.get('num_hidden_layers', 36)} layers, {cfg.get('num_attention_heads', 16)} query heads sharing "
    f"{cfg.get('num_key_value_heads', 2)} KV heads of {cfg.get('head_dim', 128)}; KV {btok:,} bytes per token (OPT-2.7B: 327,680).",
    "",
    "| Beams | KV at the end (GiB) | Fits in 8 GiB | Mode | Status | Transfer predicted / measured (GiB) | Transfer (s) | Compute (s) | Other (s) | Total (s) |",
    "|---|---|---|---|---|---|---|---|---|---|",
]
for n in (32, 64, 112, 128, 256, 512):
    kv = n * 2048 * btok
    fits = kv <= 8 * GiB
    for mo in ("ingpu",) if fits else ("baseline", "lbs"):
        r = G.get((mo, n))
        if mo == "baseline":
            pred = predict.baseline_dm(
                n,
                8 * GiB,
                n_layer=cfg.get("num_hidden_layers", 36),
                layer_tok=cfg.get("kv_bytes_per_token_per_layer", 1024),
            )
        elif mo == "lbs":
            pred = predict.lbs_dm(n, 8 * GiB, beam_tok=btok)
        else:
            pred = 0
        if not D.ok(r):
            o.append(
                f"| {n} | {kv / GiB:.2f} | {'yes' if fits else 'no'} | {mo} | {status(r)} | {f(pred / GiB)} / — | | | | |"
            )
            continue
        o.append(
            f"| {n} | {kv / GiB:.2f} | {'yes' if fits else 'no'} | {mo} | done | {f(pred / GiB)} / {f(r['h2d_bytes'] / GiB)} "
            f"| {f(r['h2d_s'])} | {f(r['compute_s'])} | {f(D.other_s(r))} | {f(r['total_s'])} |"
        )
o += [""]

# ---------------------------------------------------------------- microbenchmark
mb = D.microbench()
if mb:
    o += [
        "## Attention microbenchmark (one layer, 32 beams, 32 heads × 80, FP16)",
        "",
        f"One copy per beam, {mb['per_beam_tokens']:,} tokens: {mb['per_beam_ms']:.3f} ms.",
        "",
        "| Pool rows (distinct tokens) | Pool + mask (ms) | 8 buffers (ms) | 63 buffers (ms) |",
        "|---|---|---|---|",
    ]
    for r in mb["rows"]:
        o.append(
            f"| {r['pool_rows']:,} | {r['pool_mask_ms']:.3f} | {r['buffers_8_ms']:.3f} | {r['buffers_63_ms']:.3f} |"
        )
    o += [""]

# ---------------------------------------------------------------- checks
ch = D.checks()
if ch:
    o += [
        "## Correctness checks",
        "",
        "| Check script | FP16 | FP32 |",
        "|---|---|---|",
    ]
    for name, c in ch.items():
        fp16 = c.get("fp16_ok", c.get("ok"))
        o.append(
            f"| scripts/check_{name}.py | {'pass' if fp16 else 'FAIL'} | {'pass' if c.get('fp32_ok', c.get('ok')) else 'FAIL'} |"
        )
    o += [""]

open("results/tables.md", "w").write("\n".join(o) + "\n")
print("wrote results/tables.md")
